"""Generate the documentation that is derived from code, so it cannot drift from it.

    uv run python tools/gen_docs.py            # write docs/config-reference.md, docs/style-reference.md, docs/gallery.md
    uv run python tools/gen_docs.py --check    # exit 1 if any committed reference is out of date (CI runs this)
    uv run python tools/gen_docs.py --gallery  # also render the gallery sheets into docs/gallery/ (the docs site build runs this)

Sources: the configuration reference comes from blueprint.config.KEYS (the same table the loader validates against); the style reference from the
dataclasses in blueprint.style, with each value's trailing source comment as its description; the gallery from rendering an asymmetric test block with
the real generator. Gallery images are not committed (font rasterising differs between machines); the docs site build renders them.

Log level comes from --log-level or the BLUEPRINT_LOG_LEVEL environment variable.
"""

from __future__ import annotations

import argparse
import ast
import dataclasses
import logging
import os
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from blueprint import style as style_module  # noqa: E402
from blueprint.config import KEYS  # noqa: E402
from blueprint.layout import auto_sheet  # noqa: E402
from blueprint.licences import lookup  # noqa: E402
from blueprint.revisions import GitDates, revisions  # noqa: E402
from blueprint.sheet import Sheet, TitleInfo  # noqa: E402

log = logging.getLogger("gen_docs")
DOCS = ROOT / "docs"
GENERATED_NOTE = "<!-- Generated by tools/gen_docs.py from the source. Do not edit by hand: change the code and re-run it. -->\n\n"
EXAMPLE_DATE = date(2026, 11, 18)  # fixed, so gallery sheets do not change every day

# name, blueprint.yml lines, what the example shows
GALLERY: tuple[tuple[str, dict[str, object], str], ...] = (
    ("default", {}, "The default sheet: front, top and right views in third-angle positions, the isometric at the main scale, overall dimensions."),
    ("all-six", {"views": ("FRONT", "TOP", "BOTTOM", "LEFT", "RIGHT", "BACK", "ISOMETRIC")}, "`views:` with all six orthographic views and the isometric."),
    ("top-only", {"views": ("TOP",)}, "`views: [top]`: one view on its own, centred and drawn as large as a standard scale allows."),
    ("iso-fill", {"iso_size": None}, "`isometric: fill`: the isometric fills the space right of the views."),
    ("iso-only", {"views": ("ISOMETRIC",)}, "`views: [isometric]`: the isometric alone."),
    ("plain", {"toggles": style_module.Toggles(aged=False, stamp=False, winks=False)}, "`style: {aged: false, stamp: false, winks: false}`: drafting only."),
    ("grid", {"toggles": style_module.Toggles(grid=True)}, "`style: {grid: true}`: the faint 10 mm graph grid over the aged paper."),
)


def _md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def config_reference() -> str:
    """Markdown table of every blueprint.yml key, from blueprint.config.KEYS."""
    lines = [
        "# blueprint.yml reference\n",
        GENERATED_NOTE.strip() + "\n",
        "One `blueprint.yml` per drawing. Paths are relative to the file. Unknown keys are an error, so a typo fails the build instead of being ignored.\n",
        "| Key | Type | Default | Meaning | Example |",
        "|---|---|---|---|---|",
    ]
    for k in KEYS:
        example = f"`{k.name}: {k.example}`" if k.example else ""
        lines.append(f"| `{k.name}` | {k.kind} | {_md_cell(k.default)} | {_md_cell(k.doc)} | {_md_cell(example)} |")
    lines += ["", "## A complete example", "", "```yaml"]
    lines += [f"{k.name}: {k.example}" for k in KEYS if k.example]
    lines += ["```", ""]
    return "\n".join(lines)


def _field_comments(cls: type) -> dict[str, str]:
    """Trailing `# comment` on each field line of a dataclass, read from the source so the comment stays the one place the meaning is written."""
    source_lines = Path(style_module.__file__).read_text().splitlines()
    tree = ast.parse("\n".join(source_lines))
    out: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == cls.__name__:
            for stmt in node.body:
                if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                    line = source_lines[stmt.lineno - 1]
                    out[stmt.target.id] = line.split("#", 1)[1].strip() if "#" in line else ""
    return out


def style_reference() -> str:
    """Markdown tables of the house style's values, one per style dataclass, plus sheet sizes and scales."""
    lines = ["# House style reference\n", GENERATED_NOTE.strip() + "\n", (style_module.__doc__ or "").strip() + "\n"]
    for cls in (style_module.Palette, style_module.Lines, style_module.Type, style_module.Spacing, style_module.Toggles):
        comments = _field_comments(cls)
        lines += [f"## {cls.__name__}\n", (cls.__doc__ or "").strip() + "\n", "| Name | Value | Notes |", "|---|---|---|"]
        for f in dataclasses.fields(cls):
            value = f.default
            shown = (
                f"`{value}`"
                if not isinstance(value, str) or not value.startswith("#")
                else f"`{value}` ![](https://placehold.co/12x12/{value[1:]}/{value[1:]}.png)"
            )
            lines.append(f"| `{f.name}` | {shown} | {_md_cell(comments.get(f.name, ''))} |")
        lines.append("")
    lines += ["## Sheet sizes\n", "| Size | Width × height (mm) | SIZE field wink |", "|---|---|---|"]
    for s in style_module.SHEET_SIZES.values():
        lines.append(f"| {s.name} | {s.width:g} × {s.height:g} | {s.wink} |")
    lines += [
        "",
        "## Standard scales\n",
        "The automatic layout uses the largest of these that fits: " + ", ".join(style_module.scale_label(s) for s in style_module.STANDARD_SCALES) + ".",
        "",
    ]
    return "\n".join(lines)


def gallery_page() -> str:
    """Markdown page linking every gallery sheet with what it demonstrates."""
    lines = [
        "# Gallery\n",
        GENERATED_NOTE.strip() + "\n",
        "Each sheet is the asymmetric test block from the test suite (40 × 30 × 20 with a corner notch and a through-hole), "
        "rendered by the generator itself when the docs site is built. Click a sheet for the full-size SVG.\n",
    ]
    for name, _, what in GALLERY:
        lines += [f"## {name}\n", what + "\n", f"[![{name}](gallery/{name}.png)](gallery/{name}.svg)\n"]
    return "\n".join(lines)


def render_gallery() -> None:
    """Render every gallery sheet into docs/gallery/ as SVG and PNG."""
    from conftest import notched_block  # the test block: geometry known independently of the code under test

    out = DOCS / "gallery"
    out.mkdir(parents=True, exist_ok=True)
    block = notched_block()
    dates = GitDates(date(2026, 10, 13), "0000000", dirty=False)
    for name, opts, _ in GALLERY:
        toggles = opts.get("toggles", style_module.Toggles())
        sheet = Sheet("B", dataclasses.replace(style_module.Style(), toggles=toggles))  # type: ignore[arg-type]
        kwargs = {k: v for k, v in opts.items() if k in ("views", "iso_size")}
        layout = auto_sheet(sheet, block, captions={"FRONT": "notch top right"}, **kwargs)  # type: ignore[arg-type]
        sheet.title_block(
            TitleInfo(
                title=f"TEST BLOCK · {name.upper()}",
                drawing_number="EX-001",
                for_="the gallery",
                material="PLA is fine here",
                source="tests/conftest.py",
                drawn_by="THE GENERATOR",
                company="Example Works",
                started=dates.started,
                updated=EXAMPLE_DATE,
                revisions=revisions(dates, EXAMPLE_DATE),
                licence=lookup("MIT" if name == "plain" else "CC-BY-NC-SA-4.0"),
                copyright="© 2026 Example Works",
            ),
            layout.scale,
        )
        sheet.notes(["Example sheet for the documentation.", "Dimensions are measured from the projection, not typed."])
        sheet.save(out / name, ("svg", "png"))


def main() -> int:
    """Write or check the generated references, optionally rendering the gallery."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if a committed reference differs from what the code generates")
    ap.add_argument("--gallery", action="store_true", help="also render the gallery sheets")
    ap.add_argument("--log-level", default=os.environ.get("BLUEPRINT_LOG_LEVEL", "INFO"), choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    args = ap.parse_args()
    logging.basicConfig(level=args.log_level, format="%(asctime)s %(levelname)-5s %(name)s: %(message)s")
    pages = {DOCS / "config-reference.md": config_reference(), DOCS / "style-reference.md": style_reference(), DOCS / "gallery.md": gallery_page()}
    stale = []
    for path, text in pages.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            log.info("wrote %s", path.relative_to(ROOT))
    if stale:
        log.error("out of date: %s (run: uv run python tools/gen_docs.py)", ", ".join(map(str, stale)))
        return 1
    if args.gallery:
        render_gallery()
    return 0


if __name__ == "__main__":
    sys.exit(main())
